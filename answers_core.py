def clean_sentence(text: str) -> str:
    text = text.replace("**", "").replace("`", "")
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"^\s*[-*•]\s*", "", text)
    text = re.sub(r"^\s*\d+[.)]\s*", "", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip(" |—-")


def strip_tables(text: str) -> str:
    """Убирает ASCII- и Markdown-таблицы: в ответе они выглядят мусором."""
    result: list[str] = []
    in_table = False
    for line in text.splitlines():
        stripped = line.strip()
        if re.fullmatch(r"[-–—\s]{3,}", stripped):
            in_table = True
            continue
        if in_table:
            if not stripped:
                in_table = False
            continue
        if stripped.startswith("|") or stripped.count("|") >= 2:
            continue
        result.append(line)
    return "\n".join(result)


def sentences(text: str) -> list[str]:
    """Аккуратно режет фрагмент на предложения, не склеивая таблицы и заголовки."""
    text = strip_tables(text)
    result: list[str] = []
    buffer = ""

    def flush() -> None:
        nonlocal buffer
        if not buffer:
            return
        for part in re.split(r"(?<=[.!?])\s+", buffer):
            cleaned = clean_sentence(part)
            if 40 <= len(cleaned) <= 380:
                result.append(cleaned)
        buffer = ""

    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("---"):
            continue
        if re.fullmatch(r"[-–—\s]+", line):
            continue
        if line.startswith("|") or line.count("|") >= 2:
            continue
        if re.search(r"\S\s{2,}\S", line):
            continue
        if "](" in line:
            continue
        line = clean_sentence(line)
        if not line:
            continue
        buffer = f"{buffer} {line}".strip() if buffer else line
        if re.search(r"[.!?]$", line) or raw.lstrip().startswith(("-", "*", "•")) or len(buffer) > 360:
            flush()
    flush()
    return result


def _score_sentence(
    sentence: str,
    query_tokens: set[str],
    intent: str,
    specific_terms: set[str],
    intent_terms: tuple[str, ...],
) -> float:
    tokens = set(tokenize(sentence))
    if not tokens:
        return 0.0
    overlap = 0.0
    for token in tokens & query_tokens:
        overlap += 1.6 if len(token) >= 6 else 1.0
    specific_hits = len(tokens & specific_terms)
    intent_hits = sum(1 for term in intent_terms if term in normalize(sentence))
    length_penalty = 1.0 if 60 <= len(sentence) <= 260 else 0.75
    return (overlap + specific_hits * 1.3 + intent_hits * 0.6) * length_penalty / (1 + len(sentence) / 520)


def _jaccard(left: str, right: str) -> float:
    a, b = set(tokenize(left)), set(tokenize(right))
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


