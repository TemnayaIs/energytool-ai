def _keyword_hit(tokens: list[str], keyword: str) -> bool:
    """Ищет ключевое слово по границе слова, а не как случайную подстроку."""
    keyword = normalize(keyword)
    if not keyword:
        return False
    if " " in keyword:
        return keyword in " ".join(tokens)
    if len(keyword) <= 3:
        return keyword in tokens
    return any(token.startswith(keyword) for token in tokens)


def intent_scores(text: str) -> dict[str, float]:
    lowered = normalize(text)
    tokens = lowered.split()
    scores: dict[str, float] = {intent: 0.0 for intent in INTENT_KEYWORDS}
    for intent, keywords in INTENT_KEYWORDS.items():
        for keyword in keywords:
            if _keyword_hit(tokens, keyword):
                scores[intent] += 1.0
    for intent, markers in STRONG_MARKERS.items():
        for marker in markers:
            if _keyword_hit(tokens, marker):
                scores[intent] += 1.5
    return scores


def detect_intent(text: str, previous: str = "unknown") -> str:
    """Определяет задачу клиента по реплике или контексту диалога."""
    lowered = normalize(text)
    if not lowered:
        return "unknown"
    tokens = lowered.split()

    # Явные сигналы важнее суммы совпадений: «оптовый рынок» и «фото»
    # не должны проигрывать словам «учёт» или «счётчик».
    if any(_keyword_hit(tokens, marker) for marker in ("оптов", "орэм")) or "опт" in tokens:
        return "orem"

    reading_signal = any(
        _keyword_hit(tokens, marker)
        for marker in (
            "фото", "фотограф", "распозна", "снимок", "телеграм", "штрих",
            "считыва", "год выпуска", "многотариф", "двухтариф",
        )
    )
    accounting_anchor = any(
        _keyword_hit(tokens, marker)
        for marker in (
            "арендатор", "платформ", "цех", "магазин", "потер", "хищен",
            "склад", "тсж", "снт", "управляющ", "телеметри",
        )
    )
    if reading_signal and not accounting_anchor:
        return "reading"

    scores = intent_scores(text)
    best = max(scores, key=scores.get)
    if scores[best] <= 0:
        return "unknown"

    # Короткие уточнения и продолжения диалога не должны менять тему.
    if previous not in ("unknown", "general") and best != previous:
        if best == "general":
            return previous
        previous_score = scores.get(previous, 0.0)
        best_score = scores.get(best, 0.0)
        explicit_switch = any(
            _keyword_hit(tokens, marker) for marker in STRONG_MARKERS.get(best, ())
        )
        if previous_score >= best_score - 1.0 or not explicit_switch:
            return previous

    return best


