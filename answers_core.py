def simple_slots(text: str) -> dict:
    """Грубое извлечение слотов из текста для конкурсного сабмита.

    Веб-прототип ведёт полноценное состояние диалога, а solution.py получает
    только строку вопроса (иногда со встроенной историей). Этого достаточно,
    чтобы не задавать уточнение о том, что клиент уже сообщил.
    """
    normalized = normalize(text)
    slots: dict[str, bool] = {}

    if re.search(r"(почасов|получасов|суточн)", normalized):
        slots["has_hourly"] = True
    if re.search(r"(электроэнерг|электричеств|\bвода\b|\bводы\b|\bводе\b)", normalized):
        slots["resource"] = True
    if re.search(r"\d+\s*квт(?!\s*ч)|\d+\s*мвт|киловатт|мегаватт", normalized):
        slots["power_kw"] = True
    if re.search(r"(квт\s*ч|квтч|потреблен|расход электро)", normalized):
        slots["consumption_kwh"] = True
    if re.search(r"(област|край|республик|москв|петербург|регион|город)", normalized):
        slots["region"] = True
    if re.search(r"(категор|\bцк\b|четверт|второй ценовой|первой ценовой)", normalized):
        slots["price_category"] = True
    if re.search(r"\d+\s*(счетчик|прибор)", normalized):
        slots["meters_count"] = True
    if re.search(r"(снизить|сократить|резерв|автономн|экономи|окупаем|платеж|цель)", normalized):
        slots["goals"] = True
    return slots


def _is_general_question(text: str) -> bool:
    words = text.split()
    if len(words) <= 10:
        return True
    return bool(re.search(r"(что это|расскажите|подходит ли|как работает|в целом|вообще|с чего начать)", text))


def curated_answer(
    context: str,
    intent: str,
    slots: dict | None = None,
) -> tuple[str, str] | None:
    """Возвращает (тело ответа, уточняющий вопрос) или None."""
    slots = slots or {}
    text = normalize(context)
    if not text:
        return None

    for rule in RULES:
        if rule.intents and intent not in rule.intents:
            continue
        if all(re.search(pattern, text) for pattern in rule.patterns):
            ask = rule.ask
            if ask and rule.ask_key and slots.get(rule.ask_key):
                ask = ""
            return rule.answer, ask

    if _is_general_question(text):
        for rule in GENERIC_RULES:
            if intent in rule.intents:
                ask = rule.ask
                if ask and rule.ask_key and slots.get(rule.ask_key):
                    ask = ""
                return rule.answer, ask
    return None


