USER_LINE_RE = re.compile(r"^(?:пользователь|user|клиент)\s*:\s*(.*)$", re.IGNORECASE)


def _non_empty_lines(text: str) -> list[str]:
    return [line.strip() for line in text.splitlines() if line.strip()]


def current_question(text: str) -> str:
    """Последняя реплика пользователя.

    Если вопрос содержит встроенную историю вида «Пользователь: …», берём
    именно последнюю реплику клиента: отвечать нужно на неё, а не на весь лог.
    """
    users = [
        match.group(1).strip()
        for line in _non_empty_lines(text)
        if (match := USER_LINE_RE.match(line))
    ]
    if users:
        return users[-1]
    lines = _non_empty_lines(text)
    return lines[-1] if lines else text.strip()


def conversation_context(text: str, limit: int = 3) -> str:
    """Несколько последних реплик клиента — для интентов и уточнений."""
    users = [
        match.group(1).strip()
        for line in _non_empty_lines(text)
        if (match := USER_LINE_RE.match(line))
    ]
    if users:
        return " ".join(users[-limit:])
    return " ".join(_non_empty_lines(text))


