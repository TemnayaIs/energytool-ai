def pick_facts(
    question: str,
    intent: str,
    results: Sequence[tuple[Chunk, float]],
    limit: int = 2,
) -> list[str]:
    """Выбирает 1–2 предложения, которые действительно отвечают на вопрос."""
    query_tokens = set(expand_tokens(tokenize(question)))
    specific_terms = {
        token for token in query_tokens
        if len(token) >= 3 and token not in GENERIC_QUERY_TOKENS
    }
    intent_terms = INTENT_TERMS.get(intent, ())

    candidates: list[tuple[float, str, str, int]] = []
    rank_bonus = (3.0, 1.5, 0.6, 0.2, 0.0)
    for rank, (chunk, chunk_score) in enumerate(results[:5]):
        for sentence in sentences(chunk.text):
            lowered = normalize(sentence)
            if any(marker in lowered for marker in META_MARKERS):
                continue
            score = _score_sentence(sentence, query_tokens, intent, specific_terms, intent_terms)
            if score <= 0:
                continue
            sentence_tokens = set(tokenize(sentence))
            specific_hits = len(sentence_tokens & specific_terms)
            score += rank_bonus[min(rank, 4)]
            score += min(max(chunk_score, 0.0), 40.0) / 60.0
            score += specific_hits * 0.9
            if specific_hits == 0 and rank > 0:
                score *= 0.75
            candidates.append((score, sentence, chunk.id, specific_hits))

    if not candidates:
        return []

    candidates.sort(key=lambda item: item[0], reverse=True)
    best_score, best_sentence, best_chunk, best_hits = candidates[0]
    facts = [best_sentence]

    for score, sentence, chunk_id, specific_hits in candidates[1:]:
        if len(facts) >= limit:
            break
        if any(_jaccard(sentence, existing) > 0.55 for existing in facts):
            continue
        same_chunk = chunk_id == best_chunk
        if same_chunk and score >= best_score * 0.45:
            facts.append(sentence)
            continue
        # Факт из другого фрагмента добавляем, только если он приносит новые
        # специфичные термины и не слишком слабее лучшего.
        if specific_hits > best_hits and score >= best_score * 0.55:
            facts.append(sentence)

    return facts[:limit]
